def _line(values, days):
    """表の1列（0月,1月,…）を日数で日割り。円で返す"""
    m, r = divmod(days, 30)
    if m >= len(values) or (r and m + 1 >= len(values)):
        raise ValueError(f'{days}日は表の範囲（15月）を超えます。個別に検討してください')
    v = values[m] + (values[m + 1] - values[m]) * r / 30 if r else values[m]
    return v * 10000

def nyutsuin(nyuin_days, tsuin_days, table='I'):
    """入院期間・通院期間（日数）→ (金額[千円未満切上げ], 計算過程の文字列)"""
    T = B1 if table == 'I' else B2
    nyu_col = T[0]                       # 入院のみ（通院0）
    tsu_col = [row[0] for row in T]      # 通院のみ（入院0）
    if nyuin_days and tsuin_days:
        a = _line(nyu_col, nyuin_days); b = _line(tsu_col, nyuin_days + tsuin_days); c = _line(tsu_col, nyuin_days)
        raw = a + b - c
        how = f'入院{nyuin_days}日分{a:,.0f}円＋（総治療期間{nyuin_days + tsuin_days}日の通院分{b:,.0f}円−入院{nyuin_days}日相当の通院分{c:,.0f}円）'
    elif nyuin_days:
        raw = _line(nyu_col, nyuin_days); how = f'入院{nyuin_days}日'
    else:
        raw = _line(tsu_col, tsuin_days); how = f'通院{tsuin_days}日'
    amount = math.ceil(round(raw, 6) / 1000) * 1000
    return amount, how

def koui(grade):
    return KOUI[grade] * 10000

def days_from_treatment(treatment, jiko_date=None):
    """事案の概要の治療経過から（入院日数, 通院期間日数）。通院期間＝総治療期間−入院日数"""
    D = dt.date.fromisoformat
    inpatient = set()
    for t in treatment:
        if t['type'] == '入院':
            d = D(t['start'])
            while d <= D(t['end']): inpatient.add(d); d += dt.timedelta(days=1)
    start = min(D(t['start']) for t in treatment)
    if jiko_date: start = min(start, D(jiko_date))
    end = max(D(t['end']) for t in treatment)
    total = (end - start).days + 1
    return len(inpatient), total - len(inpatient)

